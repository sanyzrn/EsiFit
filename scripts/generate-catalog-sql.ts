/** Generates a reviewed additive snapshot; never connects to a database. Run with Bun. */
import { writeFileSync } from "node:fs";
import { EXERCISES, MUSCLE_GROUPS } from "../src/features/workouts/data/exercise-dataset";
import { FOODS } from "../src/features/nutrition/data/food-database";
const data = (value: unknown) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;
const sql = `-- Generated by scripts/generate-catalog-sql.ts; additive and idempotent.
-- Existing IDs, food nutrients/servings and user histories are preserved.
BEGIN;
INSERT INTO esifit."MuscleGroup" ("id","slug","nameFa","region")
SELECT 'catalog_m_'||md5(x->>'slug'),x->>'slug',x->>'nameFa',x->>'region'
FROM jsonb_array_elements(${data(MUSCLE_GROUPS)}) x ON CONFLICT ("slug") DO NOTHING;
INSERT INTO esifit."Exercise" ("id","slug","nameFa","equipment","movementPattern","difficulty","isUnilateral","isCompound","instructionsFa","cuesJson")
SELECT 'catalog_e_'||md5(x->>'slug'),x->>'slug',x->>'nameFa',x->>'equipment',x->>'movementPattern',x->>'difficulty',COALESCE((x->>'isUnilateral')::boolean,false),(x->>'isCompound')::boolean,x->>'instructionsFa','[]'
FROM jsonb_array_elements(${data(EXERCISES)}) x ON CONFLICT ("slug") DO NOTHING;
INSERT INTO esifit."ExerciseMuscle" ("exerciseId","muscleGroupId","role","intensity")
SELECT e."id",g."id",m->>'role',(m->>'intensity')::double precision
FROM jsonb_array_elements(${data(EXERCISES)}) x
CROSS JOIN LATERAL jsonb_array_elements(x->'muscles') m
JOIN esifit."Exercise" e ON e."slug"=x->>'slug'
JOIN esifit."MuscleGroup" g ON g."slug"=m->>'slug'
ON CONFLICT ("exerciseId","muscleGroupId") DO NOTHING;
INSERT INTO esifit."Food" ("id","slug","nameFa","category","servingAmount","servingUnit","calories","proteinG","carbsG","fatG","fiberG","sodiumMg","isPublic")
SELECT 'catalog_f_'||md5(x->>'slug'),x->>'slug',x->>'nameFa',x->>'category',(x->>'servingAmount')::double precision,x->>'servingUnit',(x->>'calories')::double precision,(x->>'proteinG')::double precision,(x->>'carbsG')::double precision,(x->>'fatG')::double precision,(x->>'fiberG')::double precision,(x->>'sodiumMg')::double precision,true
FROM jsonb_array_elements(${data(FOODS)}) x ON CONFLICT ("slug") DO NOTHING;
UPDATE esifit."Exercise" SET "nameFa"='بالا آوردن پا با تکیه‌گاه' WHERE "slug"='leg-raise-machine' AND "nameFa"='شکم دستگاه';
COMMIT;
`;
writeFileSync("docs/sql/catalog_expansion_20261025.sql", sql);
console.log(`Catalog SQL generated: ${EXERCISES.length} movements, ${FOODS.length} foods; no database writes.`);
